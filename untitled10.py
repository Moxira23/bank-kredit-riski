def hisobla_kredit_riski(row):
    risk_ball = 0

    if row['kredit_tarixi'] == 'yomon':
        risk_ball -= 50
    elif row['kredit_tarixi'] == 'yaxshi':
        risk_ball += 35
    else:
        risk_ball += 10

    daromad_qarz = row['jami_qarz'] / max(row['daromad'], 1)
    if daromad_qarz > 4:
        risk_ball -= 45
    elif daromad_qarz < 1.5:
        risk_ball += 20

    if row['kechiktirilgan_tolovlar'] > 5:
        risk_ball -= 50
    elif row['kechiktirilgan_tolovlar'] == 0:
        risk_ball += 25

    if row['ish_staji'] > 8:
        risk_ball += 20
    elif row['ish_staji'] < 2:
        risk_ball -= 30

    if row['kafil_bormi'] == 'ha':
        risk_ball += 25
        if row['kafil_daromadi'] > 5000:
            risk_ball += 15
        if row['kafil_kredit_tarixi'] == 'yaxshi':
            risk_ball += 10
    else:
        risk_ball -= 20

    if row['ish_joyi_turi'] == 'davlat':
        risk_ball += 25
    elif row['ish_joyi_turi'] == 'xususiy':
        risk_ball += 10
    elif row['ish_joyi_turi'] == 'ozini_ishi':
        risk_ball -= 10
    else:
        risk_ball -= 40

    if row['yosh'] > 55:
        risk_ball -= 15
    elif row['yosh'] < 23:
        risk_ball -= 10

    if row['oylik_majburiyat'] > row['daromad'] * 0.5:
        risk_ball -= 25

    return 1 if risk_ball > 0 else 0

