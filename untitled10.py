def oqit_model(baza):
    oz_features = ['yosh', 'daromad', 'jami_qarz', 'ish_staji', 'mavjud_kreditlar',
                   'kechiktirilgan_tolovlar', 'oylik_majburiyat', 'kafil_daromadi']

    label_encoders = {}
    kategoriklar = ['kredit_tarixi', 'kafil_bormi', 'ish_joyi_turi']

    for col in kategoriklar:
        le = LabelEncoder()
        baza[col + '_encoded'] = le.fit_transform(baza[col])
        label_encoders[col] = le
        oz_features.append(col + '_encoded')

    X = baza[oz_features]
    y = baza['kredit_berilsinmi']

    model = RandomForestClassifier(n_estimators=100, max_depth=10, random_state=42)
    model.fit(X, y)

    joblib.dump(model, MODEL_FILE)
    joblib.dump(label_encoders, 'label_encoders_50.pkl')
    joblib.dump(oz_features, 'oz_features_50.pkl')

    return model, label_encoders, oz_features

